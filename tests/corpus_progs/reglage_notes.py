        t.exo("Triceps corde 3x12 @ 25kg", "Triceps corde", [g(3, 12, kg(25))], canon="Triceps")
        t.day("Mercredi")
        dl = round(220 * (a - 0.1) / 2.5) * 2.5
        t.exo(f"Soulevé de terre : 3x3 @ {kg(dl).replace(' kg','')}kg RPE {rp}", "Soulevé de terre", [g(3, 3, kg(dl))], canon="Soulevé de terre", rpe=rp)
