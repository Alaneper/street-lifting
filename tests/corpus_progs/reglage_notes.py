    t = TB(p)
    t.raw("BLOC FORCE – 3 semaines (1RM : squat 180, bench 125, deadlift 220)").raw()
    for w, (rp, a, b) in enumerate([("7", 0.80, 5), ("8", 0.85, 3), ("9", 0.90, 2)], 1):
        t.week(f"Semaine {w}")
        t.day("Lundi")
        sq = round(180 * a / 2.5) * 2.5
        t.exo(f"Squat : {b}x1 à {int(a*100)}% puis 3x5 à -10%", "Squat", [g(b, 1, pct(int(a*100))), g(3, 5, pct(-10))], canon="Squat")
